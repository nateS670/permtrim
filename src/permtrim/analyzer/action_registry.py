"""AWS IAM action registry, backed by the policy_sentry iam-definition dataset.

The bundled dataset (``data/iam-definition.json.gz``, ~1 MB) is generated by
the open-source `policy_sentry <https://github.com/PolicySentry/policy_sentry>`_
project from AWS's official Service Authorization Reference. It enumerates
every IAM action (20,455 across 445 services at bundle time) together with its
access level, which powers two things:

1. **Wildcard expansion** — an IAM policy may grant ``s3:Get*`` while the
   audit log records ``s3:GetObject``; the registry tells us exactly which
   concrete actions a wildcard pattern covers (and how many).
2. **Hallucination detection (Task 4 guardrail)** — an LLM proposing
   ``s3:GetObjekt`` is caught because the action does not exist.

CloudTrail event names occasionally differ from the IAM action name (the
classic case: the ``ListBuckets`` event is authorized by
``s3:ListAllMyBuckets``); ``normalize()`` applies the known exceptions.
Console sign-in events (``signin:ConsoleLogin``) are not IAM-governed and
normalize to ``None``.
"""

from __future__ import annotations

import fnmatch
import gzip
import json
import logging
from functools import lru_cache
from pathlib import Path
from typing import Any

__all__ = ["ActionRegistry", "load_default_registry"]

LOGGER = logging.getLogger(__name__)

_DATASET_PATH = Path(__file__).parent / "data" / "iam-definition.json.gz"

DATASET_SOURCE = "policy_sentry iam-definition (generated from the AWS Service Authorization Reference)"

# CloudTrail event name -> IAM action name (lowercased). These are the
# documented cases where the logged event name differs from the action that
# authorizes it.
_EVENT_NAME_EXCEPTIONS: dict[str, str] = {
    "s3:listbuckets": "s3:listallmybuckets",
}

# Services whose logged events are not governed by IAM identity policies.
_NON_IAM_SERVICES = frozenset({"signin"})


class ActionRegistry:
    """Read-only lookup of known AWS IAM actions and services.

    All action strings are handled lowercased (IAM action matching is
    case-insensitive); ``expand``/``count_matching`` return lowercase
    ``service:action`` strings.
    """

    def __init__(self, services: dict[str, dict[str, Any]]) -> None:
        # prefix (lowercase) -> {action_name (lowercase) -> privilege record}
        self._actions: dict[str, dict[str, dict[str, Any]]] = {}
        for service in services.values():
            prefix = service["prefix"].lower()
            self._actions[prefix] = {name.lower(): record for name, record in service["privileges"].items()}
        self.service_count = len(self._actions)
        self.action_count = sum(len(actions) for actions in self._actions.values())

    # ------------------------------------------------------------ existence

    def service_exists(self, service: str) -> bool:
        """True if ``service`` is a known IAM service prefix (``s3``, ``ec2``)."""
        return service.lower() in self._actions

    def action_exists(self, action: str) -> bool:
        """True if ``service:name`` is a known IAM action (case-insensitive)."""
        try:
            service, name = action.lower().split(":", 1)
        except ValueError:
            return False
        return name in self._actions.get(service, {})

    def access_level(self, action: str) -> str | None:
        """Dataset access level of an action (Read/Write/List/...), if known."""
        try:
            service, name = action.lower().split(":", 1)
        except ValueError:
            return None
        record = self._actions.get(service, {}).get(name)
        return record.get("access_level") if record else None

    def canonical(self, action: str) -> str | None:
        """Canonical (dataset-cased) form of an action, e.g. ``s3:getobject``
        -> ``s3:GetObject``. Returns ``None`` for unknown actions."""
        try:
            service, name = action.lower().split(":", 1)
        except ValueError:
            return None
        actions = self._actions.get(service, {})
        record = actions.get(name)
        if record is None:
            return None
        return f"{service}:{record['privilege']}"

    # ------------------------------------------------------------ normalization

    def normalize(self, action: str) -> str | None:
        """Map an observed audit-log action to the IAM action that governs it.

        Returns ``None`` for actions that are not governed by IAM identity
        policies (console sign-ins) or that carry no service prefix.
        """
        lowered = action.lower()
        if ":" not in lowered:
            return None
        service = lowered.split(":", 1)[0]
        if service in _NON_IAM_SERVICES:
            return None
        return _EVENT_NAME_EXCEPTIONS.get(lowered, lowered)

    # ------------------------------------------------------------ wildcards

    def expand(self, pattern: str, limit: int | None = None) -> list[str]:
        """Concrete known actions matching an IAM action pattern.

        Args:
            pattern: Pattern such as ``s3:Get*``, ``ec2:*`` or ``*``
                (case-insensitive; IAM only gives meaning to ``*`` and ``?``).
            limit: Stop after this many results (expansions can be huge).

        Returns:
            Lowercase ``service:action`` strings, sorted.
        """
        lowered = pattern.lower()
        if lowered in {"*", "*:*"}:
            candidates = (
                f"{service}:{name}" for service, actions in self._actions.items() for name in actions
            )
        else:
            try:
                service, name_pattern = lowered.split(":", 1)
            except ValueError:
                return []
            candidates = (
                f"{service}:{name}"
                for name in self._actions.get(service, {})
                if fnmatch.fnmatchcase(name, name_pattern)
            )
        results = sorted(candidates)
        return results if limit is None else results[:limit]

    def count_matching(self, pattern: str) -> int:
        """Number of known concrete actions an IAM pattern covers."""
        return len(self.expand(pattern))

    def unmatched_within(self, pattern: str, used_actions: set[str]) -> list[str]:
        """Concrete actions covered by ``pattern`` but absent from ``used_actions``.

        Capped for reporting; used to show *examples* of what a wildcard
        grants beyond observed usage.
        """
        return [action for action in self.expand(pattern) if action not in used_actions]

    # ------------------------------------------------------------ reporting

    def dataset_summary(self) -> dict[str, Any]:
        return {
            "source": DATASET_SOURCE,
            "services": self.service_count,
            "actions": self.action_count,
        }


@lru_cache(maxsize=1)
def _cached_load(path: str) -> ActionRegistry:
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        raw = json.load(handle)
    services = {key: value for key, value in raw.items() if key != "policy_sentry_schema_version"}
    registry = ActionRegistry(services)
    LOGGER.debug("IAM action registry loaded: %s", registry.dataset_summary())
    return registry


def load_default_registry() -> ActionRegistry:
    """Load the bundled dataset (cached per process; ~1s first call)."""
    return _cached_load(str(_DATASET_PATH))
