"""Action-level validated policy -> Terraform HCL rendering.

The tightened policy is rendered as a heredoc JSON document inside an
``aws_iam_policy`` resource — the same pattern Terraform's IAM module uses.
Heredoc avoids the escaping maze of ``jsonencode()``-on-generated-data and
keeps the policy byte-identical to what the guardrail validated: what you read
in the plan is exactly what was validated.

What "validated" means here — read this before applying:

* ACTION level only: every action exists in the AWS dataset, every used
  action is still covered, no action outside the original grants.
* Resource scopes are carried over from the original policies where the
  analyzer recorded them; statements with ``Resource: "*"`` are a fallback
  that MUST be scoped during plan review (flagged inline below).
* permtrim does NOT attach or replace anything: this file creates the
  policy object only. Detaching the old policies and attaching this one is
  a deliberate, manual step (see the header comment).
* The principal may have a permission boundary (report shows it): effective
  permissions are the intersection, which permtrim does not evaluate.
"""

from __future__ import annotations

import json
import re
from typing import Any

__all__ = ["policy_to_hcl", "terraform_sanitize_name", "TERRAFORM_HEADER"]

TERRAFORM_HEADER = """\
# ---------------------------------------------------------------------------
# Generated by permtrim (least-privilege tightener) — ACTION-LEVEL VALIDATED
#
# This policy passed permtrim's guardrails at the ACTION level:
#   1. every action exists in the AWS action dataset (no hallucinations)
#   2. every action the principal used in the audit window is still allowed
#   3. no action outside the principal's original grants is introduced
#   4. resource scopes are not wider than the original grants
#
# It does NOT replace anything by itself: this file only creates the
# aws_iam_policy object. Detach the old policies and attach this one
# manually (aws_iam_user_policy_attachment / aws_iam_role_policy_attachment).
# Review before apply — especially any Resource: "*" fallback below, and
# remember a permission boundary further intersects these permissions.
# ---------------------------------------------------------------------------
"""

_UNSAFE_NAME = re.compile(r"[^a-zA-Z0-9_]")


def terraform_sanitize_name(name: str) -> str:
    """IAM entity name -> Terraform-safe resource name suffix."""
    sanitized = _UNSAFE_NAME.sub("_", name)
    if sanitized and sanitized[0].isdigit():
        sanitized = f"p_{sanitized}"
    return sanitized or "unnamed"


def policy_to_hcl(principal: str, policy_document: dict[str, Any]) -> str:
    """Render one tightened policy as a Terraform ``aws_iam_policy`` resource.

    Args:
        principal: ``"user:alice"`` / ``"role/deploy-ci"`` style label used
            in resource names and comments.
        policy_document: The verified policy document (``Version``/``Statement``).

    Returns:
        HCL source text (with the verification header).
    """
    resource_name = terraform_sanitize_name(principal.replace(":", "_"))
    document = json.dumps(policy_document, indent=2, ensure_ascii=False)
    # heredoc content must not contain a line consisting of the delimiter
    return (
        f"{TERRAFORM_HEADER}"
        f"# principal: {principal}\n"
        f'resource "aws_iam_policy" "permtrim_{resource_name}" {{\n'
        f'  name        = "permtrim-least-privilege-{resource_name}"\n'
        f'  description = "permtrim: least-privilege policy for {principal} (guardrail-verified)"\n'
        f"\n"
        f"  policy = <<-EOT\n"
        f"{_indent(document, '    ')}"
        f"\n  EOT\n"
        f"}}\n"
    )


def _indent(text: str, prefix: str) -> str:
    return "\n".join(prefix + line if line else line for line in text.splitlines())
